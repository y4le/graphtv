// Builds the landing-page reference index from real TVmaze episode ratings.
//
// The generated module is committed so the landing page never waits on a
// provider. Rebuild deliberately when the hand-picked index changes:
//
//   node scripts/build-show-index.mjs

import fs from 'node:fs/promises'
import path from 'node:path'

const rootDir = process.cwd()
const outputFile = path.join(rootDir, 'src/data/showIndexData.js')
const SECTION_SPECS = [
  {
    id: 'start-here',
    title: "Yale's picks",
    shows: [
      { query: 'Breaking Bad' },
      { query: 'The Sopranos' },
      { query: 'The Wire' },
      { query: 'Game of Thrones' },
      { query: 'Mad Men' },
      { query: 'Better Call Saul' },
      { query: 'Succession' },
      { query: 'Severance' },
      { query: 'Chernobyl' },
      { query: 'Fleabag' },
      { query: 'The Bear' },
      { query: 'Andor' }
    ]
  },
  {
    id: 'long-runs',
    title: 'Long runs',
    shows: [
      { query: 'The Simpsons' },
      { query: 'Supernatural' },
      { query: "Grey's Anatomy" },
      { query: 'Doctor Who', title: 'Doctor Who (2005)' },
      { query: 'Friends' },
      { query: 'Seinfeld' },
      { query: 'The Office', title: 'The Office (US)' },
      { query: "It's Always Sunny in Philadelphia" }
    ]
  }
]

async function main() {
  const sections = []
  for (const section of SECTION_SPECS) {
    const rows = []
    for (const spec of section.shows) {
      const row = await loadIndexRow(spec)
      rows.push(row)
      console.log(
        `${section.title}: ${row.title} — ${row.episodes} rated episodes`
      )
    }
    sections.push({ id: section.id, title: section.title, rows })
  }

  const moduleSource = renderModule({
    builtAt: new Date().toISOString().slice(0, 10),
    source: 'tvmaze',
    sections
  })

  await fs.writeFile(outputFile, moduleSource)
  console.log(`Wrote ${path.relative(rootDir, outputFile)}.`)
}

async function loadIndexRow(spec) {
  const show = await fetchJson(
    `https://api.tvmaze.com/singlesearch/shows?q=${encodeURIComponent(spec.query)}&embed=episodes`
  )
  const tvmazeEpisodes = (show._embedded?.episodes ?? [])
    .filter(
      (episode) =>
        episode.season > 0 &&
        (!episode.airdate ||
          episode.airdate <= new Date().toISOString().slice(0, 10))
    )
    .sort(compareEpisodes)
  const episodeRatings = tvmazeEpisodes.map((episode) => ({
    season: episode.season,
    episode: episode.number,
    rating: parseRating(episode.rating?.average)
  }))
  const lastRatedIndex = episodeRatings.findLastIndex(
    ({ rating }) => rating !== null
  )
  const ratings = episodeRatings.slice(0, lastRatedIndex + 1)

  if (ratings.length < 5) {
    throw new Error(`${show.name} has fewer than five rated TVmaze episodes.`)
  }

  const missing = ratings.filter(({ rating }) => rating === null)
  if (missing.length > 0) {
    const labels = missing
      .slice(0, 5)
      .map(({ season, episode }) => `S${season}E${episode}`)
      .join(', ')
    throw new Error(
      `${show.name} has ${missing.length} unrated TVmaze episodes (${labels}${missing.length > 5 ? ', …' : ''}).`
    )
  }

  const datedEpisodes = tvmazeEpisodes.filter((episode) => episode.airdate)
  const startYear = getYear(datedEpisodes[0]?.airdate ?? show.premiered)
  const endYear = getYear(datedEpisodes.at(-1)?.airdate ?? show.ended)

  return {
    id: `tvmaze:${show.id}`,
    title: spec.title ?? show.name,
    startYear,
    endYear,
    running: show.status === 'Running' || show.status === 'In Development',
    episodes: ratings.length,
    ratings: ratings.map(({ rating }) => Math.round(rating * 10))
  }
}

function compareEpisodes(left, right) {
  return left.season - right.season || left.number - right.number
}

function parseRating(value) {
  if (value === null || value === undefined || value === '') {
    return null
  }
  const rating = Number(value)
  return Number.isFinite(rating) && rating > 0 ? rating : null
}

function getYear(value) {
  const match = String(value ?? '').match(/^\d{4}/u)
  return match ? Number(match[0]) : null
}

async function fetchJson(url) {
  const response = await fetch(url)
  const data = await response.json().catch(() => null)

  if (!response.ok) {
    throw new Error(`${response.status} ${response.statusText} for ${url}`)
  }

  return data
}

function renderModule(data) {
  return `// Generated by scripts/build-show-index.mjs. Do not edit by hand.\n\nexport const SHOW_INDEX = Object.freeze(${JSON.stringify(data, null, 2)})\n`
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
